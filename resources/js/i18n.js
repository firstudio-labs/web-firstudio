let currentLocale = DEFAULT_LOCALE;

export function getLocale() {
  return currentLocale;
}

export function getStoredLocale() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'id' || stored === 'en') {
      return stored;
    }
  } catch {
    /* ignore */
  }
  return DEFAULT_LOCALE;
}

function t(key) {
  const dict = translations[currentLocale] || translations[DEFAULT_LOCALE];
  return dict[key] ?? translations[DEFAULT_LOCALE][key] ?? key;
}

export function applyLocale(locale) {
  currentLocale = locale === 'en' ? 'en' : 'id';
  document.documentElement.lang = currentLocale;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    const value = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      if (el.hasAttribute('placeholder')) {
        el.placeholder = value;
      }
    } else {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.placeholder = t(key);
  });

  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria');
    if (key) el.setAttribute('aria-label', t(key));
  });

  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (key) el.innerHTML = t(key);
  });

  document.querySelectorAll('[data-cms-locale]').forEach((el) => {
    const id = el.getAttribute('data-cms-id') ?? el.dataset.cmsId ?? '';
    const fallbackKey = el.getAttribute('data-cms-fallback-i18n');
    const enRaw = el.getAttribute('data-cms-en') ?? el.dataset.cmsEn ?? '';
    const en = enRaw.trim() || (fallbackKey ? t(fallbackKey) : id);
    el.textContent = currentLocale === 'en' ? en : id;
  });

  document.querySelectorAll('[data-cms-locale-html]').forEach((el) => {
    const id = el.getAttribute('data-cms-id') ?? el.dataset.cmsId ?? '';
    const fallbackKey = el.getAttribute('data-cms-fallback-i18n');
    const enRaw = el.getAttribute('data-cms-en') ?? el.dataset.cmsEn ?? '';
    const en = enRaw.trim() || (fallbackKey ? t(fallbackKey) : id);
    el.innerHTML = currentLocale === 'en' ? en : id;
  });

  document.querySelectorAll('[data-locale-toggle]').forEach((btn) => {
    const btnLocale = btn.getAttribute('data-locale-toggle');
    const isActive = btnLocale === currentLocale;
    btn.setAttribute('aria-pressed', isActive ? 'true' : 'false');
    btn.classList.toggle('locale-toggle__btn--active', isActive);
  });
}

export function setLocale(locale) {
  const next = locale === 'en' ? 'en' : 'id';
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* ignore */
  }
  applyLocale(next);
  document.dispatchEvent(new CustomEvent('localechange', { detail: { locale: next } }));
}

export function initI18n() {
  currentLocale = getStoredLocale();
  applyLocale(currentLocale);

  document.querySelectorAll('[data-locale-toggle]').forEach((btn) => {
    btn.addEventListener('click', () => {
      const locale = btn.getAttribute('data-locale-toggle');
      if (locale) setLocale(locale);
    });
  });
}

/** Inline-safe: run before paint to set html lang */
export function bootstrapLocaleFromStorage() {
  if (typeof document === 'undefined') return;
  const locale = getStoredLocale();
  document.documentElement.lang = locale;
}
